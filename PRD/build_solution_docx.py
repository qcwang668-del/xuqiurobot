def style_run(run, size=None, bold=None, color=None):
    run.font.name = FONT
    run._element.get_or_add_rPr()
    rfonts = run._element.rPr.get_or_add_rFonts()
    rfonts.set(qn("w:ascii"), FONT)
    rfonts.set(qn("w:hAnsi"), FONT)
    rfonts.set(qn("w:eastAsia"), FONT)
    if size:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)

def para(text, size=10.5, bold=False, style=None, align=None, color=None):
    p = doc.add_paragraph(style=style)
    run = p.add_run(text)
    style_run(run, size=size, bold=bold, color=color)
    if align is not None:
        p.alignment = align
    return p

def h1(text):
    p = doc.add_heading("", level=1)
    run = p.add_run(text)
    style_run(run, size=16, bold=True, color=(0, 0, 0))

def h2(text):
    p = doc.add_heading("", level=2)
    run = p.add_run(text)
    style_run(run, size=13, bold=True, color=(0, 0, 0))

def h3(text):
    p = doc.add_heading("", level=3)
    run = p.add_run(text)
    style_run(run, size=11.5, bold=True, color=(0, 0, 0))

def bullets(items):
    for it in items:
        para(it, style="List Bullet")

def numbers(items):
    for it in items:
        para(it, style="List Number")

def add_table(headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    for i, htxt in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(htxt)
        style_run(run, size=10, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(val)
            style_run(run, size=10)
    doc.add_paragraph()
    return t

